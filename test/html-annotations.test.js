const assert=require('assert');
const {digest,locateText,locateImage}=require('../plugin/html-annotations');
const core=require('../plugin/reading-core');
const text='Introduction. Same quote. Middle. Same quote. End.';
const start=text.lastIndexOf('Same quote.');
const anchor={kind:'text',occurrences:2,exact:'Same quote.',start,end:start+11,documentHash:digest(text),prefix:'Middle. ',suffix:' End.'};
assert.deepStrictEqual(locateText(text,anchor),{start,end:start+11});
const shifted='New section. '+text;
assert.strictEqual(locateText(shifted,anchor).start,shifted.lastIndexOf('Same quote.'));
assert.strictEqual(locateText('Same quote. Same quote.',anchor),null);
assert.strictEqual(locateText('Quote was removed.',anchor),null);
assert.strictEqual(locateText('Introduction. Same quote. End.',anchor),null,'remaining duplicate must not steal removed annotation');
const image={kind:'image',hash:'old',source:'a.png',context:'caption'};
assert.strictEqual(locateImage([{element:1,payload:{hash:'new',source:'a.png',context:'caption'}}],image),null);
assert.strictEqual(locateImage([{element:1,payload:image},{element:2,payload:image}],image),null);
assert.strictEqual(locateImage([{element:2,payload:{...image,context:'other caption'}}],image),null);
assert.strictEqual(locateImage([{element:1,payload:image},{element:2,payload:{...image,context:'elsewhere'}}],image),1);
const block=core.buildAnnotationBlock({selectedText:'Same quote.',note:'thought',htmlAnchor:anchor});
assert.deepStrictEqual(JSON.parse(block.match(/^- html_anchor: (.*)$/m)[1]),anchor);
assert(!core.buildAnnotationBlock({selectedText:'legacy'}).includes('html_anchor'));
console.log('HTML text/image anchors, ambiguity, replacements and record format passed');
